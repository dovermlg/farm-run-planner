"""Regenerate direct config accessors. Development only; no runtime reflection."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = root / 'src/main/java/com/classictreerun'
items = re.findall(
    r'@ConfigItem\(keyName="([^"]+)"[^\n]*\)\s+default\s+\S+\s+(\w+)\(\)',
    (source / 'ClassicTreeRunConfig.java').read_text(encoding='utf-8'))
assert len(items) == len(set(key for key, method in items))
lines = [
    'package com.classictreerun;', '',
    'import java.util.LinkedHashMap;', 'import java.util.Map;', 'import java.util.Set;', '',
    '/** Direct accessors generated by tools/generate-config-values.py; no runtime reflection. */',
    'final class ConfigValues', '{',
    '    private ConfigValues() { }',
    '    static final Set<String> KEYS = Set.of(',
    ',\n'.join('        "' + key + '"' for key, method in items) + ');', '',
    '    static Map<String,String> read(ClassicTreeRunConfig config)', '    {',
    '        Map<String,String> values = new LinkedHashMap<>();']
lines += ['        values.put("' + key + '", wire(config.' + method + '()));' for key, method in items]
lines += ['        return values;', '    }', '',
          '    private static String wire(Object value)',
          '    { return value instanceof Enum ? ((Enum<?>) value).name() : String.valueOf(value); }', '}', '']
(source / 'ConfigValues.java').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
print('Generated direct access for', len(items), 'config values.')
